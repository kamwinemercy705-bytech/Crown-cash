<?php

/*
|--------------------------------------------------------------------------
| Crown Cash — MongoDB Configuration
|--------------------------------------------------------------------------
*/

require_once __DIR__ . "/vendor/autoload.php";

try {

    /*
    |--------------------------------------------------------------------------
    | Get MongoDB URI from Render environment variables
    |--------------------------------------------------------------------------
    */

    $uri = getenv("MONGODB_URI");

    if (!$uri) {

        throw new Exception(
            "MONGODB_URI environment variable is not configured."
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Connect to MongoDB Atlas
    |--------------------------------------------------------------------------
    */

    $client = new MongoDB\Client($uri);


    /*
    |--------------------------------------------------------------------------
    | Select Crown Cash Database
    |--------------------------------------------------------------------------
    */

    $database = $client->selectDatabase("crowncash");


    /*
    |--------------------------------------------------------------------------
    | Users Collection
    |--------------------------------------------------------------------------
    */

    $users = $database->users;


    /*
    |--------------------------------------------------------------------------
    | Investments Collection
    |--------------------------------------------------------------------------
    */

    $investments = $database->investments;


    /*
    |--------------------------------------------------------------------------
    | Transactions Collection
    |--------------------------------------------------------------------------
    */

    $transactions = $database->transactions;


    /*
    |--------------------------------------------------------------------------
    | Deposits Collection
    |--------------------------------------------------------------------------
    */

    $deposits = $database->deposits;


    /*
    |--------------------------------------------------------------------------
    | Withdrawals Collection
    |--------------------------------------------------------------------------
    */

    $withdrawals = $database->withdrawals;


    /*
    |--------------------------------------------------------------------------
    | Referrals Collection
    |--------------------------------------------------------------------------
    */

    $referrals = $database->referrals;


    /*
    |--------------------------------------------------------------------------
    | Audit Logs Collection
    |--------------------------------------------------------------------------
    */

    $audit_logs = $database->audit_logs;


} catch (Throwable $e) {

    /*
    |--------------------------------------------------------------------------
    | Log Database Error
    |--------------------------------------------------------------------------
    */

    error_log(
        "CROWN CASH MONGODB ERROR: " .
        $e->getMessage()
    );


    /*
    |--------------------------------------------------------------------------
    | Return Error
    |--------------------------------------------------------------------------
    */

    http_response_code(500);

    header(
        "Content-Type: application/json; charset=UTF-8"
    );

    echo json_encode([

        "success" => false,

        "message" =>
            "Database connection failed."

    ]);

    exit;
}

?>